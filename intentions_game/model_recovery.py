"""Model recovery for H vs. M1: can the comparison tell which model generated the data?

M1 can be read as a moment-matched shortcut of H, so the two make similar
predictions; this checks whether 126 trials suffice to tell them apart.

Ground truth: every other one of the 103 participants (52 sets). M1 data come from the authors'
HBI estimates for M1; H data from the same sets mapped to H (tau = v_ref / sqrt(2)). For each
set and each generator, simulate 126 responses on that participant's real payoffs and partner
choices, then fit BOTH models blind (starts: prior mean and random draws, never the truth) with
the same MAP + Laplace procedure as fit.py. Both models have 6 parameters and the same prior.

Usage: python -I model_recovery.py           -> results/model_recovery_H_M1.npz (checkpointed)
       python -I model_recovery.py analyze   -> confusion matrix and Bayes factors
"""
import sys
import time
from functools import partial
from pathlib import Path

import jax
import jax.numpy as np
import numpy as onp

sys.path.insert(0, str(Path(__file__).resolve().parent))
import memo_models as mm  # noqa: E402
from recovery_h import truth_sets  # noqa: E402

OUT = Path(__file__).resolve().parent / "results" / "model_recovery_H_M1.npz"
GENERATORS = ["H", "M1"]
FITTED = ["H", "M1"]


def simulate(model, params, data, rng):
    netp, _ = jax.jit(partial(mm.model_netp, model))(np.asarray(params), np.asarray(data))
    sim = onp.array(data, dtype=float)
    sim[:, 6] = onp.where(rng.random(126) < onp.asarray(netp), 1.0, 2.0)
    return sim


def run():
    from fit import fit_one   # noqa: E402
    P, rows = truth_sets()
    rows = rows[::2]
    rng = onp.random.default_rng(7)
    n = len(rows)
    log_ev = onp.full((n, len(GENERATORS), len(FITTED)), onp.nan)
    ok = onp.zeros_like(log_ev, dtype=bool)
    t0 = time.time()
    for i, (pid, g, h_params) in enumerate(rows):
        m1_params = onp.concatenate([h_params[:4], h_params[4:6] + 0.5 * onp.log(2.0)])
        truth = {"H": h_params, "M1": m1_params}
        for gi, gen in enumerate(GENERATORS):
            sim = simulate(gen, truth[gen], P[pid]["data"], rng)
            for fi, fm in enumerate(FITTED):
                starts = [onp.zeros(6), rng.normal(0, 1.0, 6)]
                _, _, ev, good, _ = fit_one(fm, np.asarray(sim), starts, rng)
                log_ev[i, gi, fi], ok[i, gi, fi] = ev, good
        print(f"{i + 1}/{n} {g} {pid}: logBF(H-M1) | gen H = {log_ev[i, 0, 0] - log_ev[i, 0, 1]:+.2f}, "
              f"gen M1 = {log_ev[i, 1, 0] - log_ev[i, 1, 1]:+.2f} ({time.time() - t0:.0f}s)", flush=True)
        onp.savez(OUT, ids=onp.array([r[0] for r in rows]), groups=onp.array([r[1] for r in rows]),
                  log_ev=log_ev, ok=ok, done=i + 1, generators=onp.array(GENERATORS),
                  fitted=onp.array(FITTED))


def analyze():
    from bms import rfx_bms
    z = onp.load(OUT)
    done = int(z["done"])
    ev, ok = z["log_ev"][:done], z["ok"][:done]
    print(f"n = {done} parameter sets x 2 generators; fits ok: {ok.mean():.3f}\n")
    print(f"{'generated by':14s} {'H wins':>8s} {'M1 wins':>8s} {'|logBF|>1 correct':>18s} "
          f"{'|logBF|>1 wrong':>16s} {'median logBF(gen-other)':>24s} {'RFX xp(gen)':>12s}")
    for gi, gen in enumerate(GENERATORS):
        d = ev[:, gi, 0] - ev[:, gi, 1]             # log BF H - M1
        correct = d if gen == "H" else -d
        freq, xp, _ = rfx_bms(ev[:, gi, :])
        print(f"{gen:14s} {(d > 0).mean():8.0%} {(d < 0).mean():8.0%} {(correct > 1).mean():18.0%} "
              f"{(correct < -1).mean():16.0%} {onp.median(correct):24.2f} {xp[gi]:12.3f}")


if __name__ == "__main__":
    analyze() if len(sys.argv) > 1 and sys.argv[1] == "analyze" else run()
