"""Protected exceedance probabilities (Rigoux et al., 2014) for every model comparison reported so far.

Usage: python -I pxp_report.py
"""
import sys
from pathlib import Path

import numpy as onp

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bms import protected_bms, RES  # noqa: E402
from data import FIT_ORDER, load_hbi  # noqa: E402


def load(group):
    z5 = onp.load(RES / f"laplace_{group}.npz")
    zh = onp.load(RES / f"laplace_{group}_H.npz")
    zi = onp.load(RES / f"laplace_{group}_I.npz")
    assert (z5["ids"] == zh["ids"]).all() and (z5["ids"] == zi["ids"]).all()
    ev = dict(zip(FIT_ORDER, z5["log_ev"].T))
    ev["H"], ev["I"] = zh["log_ev"][:, 0], zi["log_ev"][:, 0]
    fc = RES / f"laplace_{group}_C.npz"
    if fc.exists():
        zc = onp.load(fc)
        if int(zc["done"]) == zc["log_ev"].shape[0]:
            assert (z5["ids"] == zc["ids"]).all()
            ev["C"] = zc["log_ev"][:, 0]
    return ev


def family(ev, members):
    return onp.logaddexp.reduce(onp.column_stack([ev[m] for m in members]), axis=1) - onp.log(len(members))


def row(label, names, mat):
    freq, xp, pxp, bor = protected_bms(mat)
    win = int(onp.argmax(xp))
    print(f"  {label:44s} winner {names[win]:9s} freq {freq[win]:.2f}  xp {xp[win]:.3f}  "
          f"pxp {pxp[win]:.3f}  BOR {bor:.3f}")


if __name__ == "__main__":
    comparisons = [
        ("5 published models", FIT_ORDER),
        ("6 models (+H)", FIT_ORDER + ["H"]),
        ("7 models (+H, I)", FIT_ORDER + ["H", "I"]),
        ("H vs M1", ["H", "M1"]),
        ("H vs M3", ["H", "M3"]),
        ("H vs M4", ["H", "M4"]),
        ("I vs M4", ["I", "M4"]),
    ]
    for g, label in (("g1", "BPD"), ("g2", "Controls")):
        ev = load(g)
        hbi = load_hbi(g)
        win = int(onp.argmax(hbi["exceedance_prob"]))
        print(f"\n=== {label}")
        print(f"  {'authors HBI, 5 models':44s} winner {FIT_ORDER[win]:9s} freq {hbi['model_frequency'][win]:.2f}  "
              f"xp {hbi['exceedance_prob'][win]:.3f}  pxp {hbi['protected_exceedance_prob'][win]:.3f}")
        extra = [("8 models (+H, I, C)", FIT_ORDER + ["H", "I", "C"]), ("C vs I", ["C", "I"]),
                 ("C vs H", ["C", "H"]), ("C vs M1", ["C", "M1"])] if "C" in ev else []
        for name, models in comparisons + extra:
            row(name, models, onp.column_stack([ev[m] for m in models]))
        fams = {
            "family: contagion yes (M1,M3) vs no (M2,M4)": (["contagion", "none"], [["M1", "M3"], ["M2", "M4"]]),
            "family: insertion yes (M1,M2) vs no (M3,M4)": (["insertion", "none"], [["M1", "M2"], ["M3", "M4"]]),
        }
        for name, (labels, members) in fams.items():
            row(name, labels, onp.column_stack([family(ev, m) for m in members]))

    # model recovery: does the protected version still recover the generator?
    z = onp.load(RES / "model_recovery_H_M1.npz")
    print("\n=== Model recovery H vs M1 (simulated)")
    for gi, gen in enumerate(["H", "M1"]):
        row(f"generated by {gen}", ["H", "M1"], z["log_ev"][:int(z["done"]), gi, :])
