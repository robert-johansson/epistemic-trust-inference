"""Data for Fig. 5: the form of the theory of others (Section 4.6).

(A) Family tests, as in intentions_game/family_report.py: estimated share of each group described by the
    intent representation {I, C} (vs competitiveness {Beta, M1-M4, H}) and by coupled self-other models
    {M1, H} (vs M4), with the 95% credible interval of that share from the random-effects Dirichlet
    posterior (two families -> Beta(alpha_plotted, alpha_other)) and the protected exceedance
    probability of the plotted family.
(B) Split-half test, as in intentions_game/split_half.py analyze: log Bayes factor C vs H estimated from
    phase 1 and phase-2 trials 1-27, and accuracy on the held-out phase-2 trials 28-54.

Usage (from the project root):
  uv run python -I figures/scripts/export_fig5_form.py
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "intentions_game"))

import numpy as onp  # noqa: E402
from scipy.stats import beta as beta_dist, spearmanr, rankdata  # noqa: E402
from bms import rfx_bms, protected_bms, RES  # noqa: E402
from pxp_report import load, family  # noqa: E402
from data import load_participants  # noqa: E402

OUT = ROOT / "figures" / "data"

# ---------------- (A) family tests ----------------
TESTS = [("intent", "representation", [["I", "C"], ["Beta", "M1", "M2", "M3", "M4", "H"]]),
         ("coupled", "coupling", [["M1", "H"], ["M4"]])]
rows = []
for g, label in (("g1", "BPD"), ("g2", "Controls")):
    ev = load(g)
    for fam_name, test, members in TESTS:
        fam_ev = onp.column_stack([family(ev, m) for m in members])
        freq, xp, pxp, bor = protected_bms(fam_ev)
        _, _, alpha = rfx_bms(fam_ev)
        lo, hi = beta_dist.ppf([0.025, 0.975], alpha[0], alpha[1])
        rows.append([test, label, fam_name, f"{freq[0]:.4f}", f"{lo:.4f}", f"{hi:.4f}", f"{pxp[0]:.4f}", f"{bor:.4f}"])
        print(f"  {label:8s} {test:14s} share {fam_name} {freq[0]:.2f} [{lo:.2f}, {hi:.2f}]  pxp {pxp[0]:.3f}  BOR {bor:.3f}")
with open(OUT / "fig5_families.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["test", "group", "family", "share", "lo", "hi", "pxp", "bor"])
    w.writerows(rows)
print("wrote fig5_families.csv")
# rows for the figure (y position, share, interval, pxp label, colour), generated so nothing is typed by hand
YPOS = {("representation", "BPD"): 4, ("representation", "Controls"): 3, ("coupling", "BPD"): 1.6, ("coupling", "Controls"): 0.6}
items = []
for test, label, fam_name, share, lo, hi, pxp, bor in rows:
    col = "groupBPD" if label == "BPD" else "groupControls"
    pxp_label = f"{float(pxp):.2f}".lstrip("0")          # e.g. 0.0667 -> ".07"
    items.append(f"{YPOS[(test, label)]}/{share}/{lo}/{hi}/{pxp_label}/{col}")
with open(OUT / "fig5_rows.tex", "w") as f:
    f.write("% generated by scripts/export_fig5_form.py from fig5_families.csv -- do not edit\n")
    f.write("\\def\\figfiverows{" + ", ".join(items) + "}\n")
print("wrote fig5_rows.tex")

# ---------------- (B) split-half ----------------
P = load_participants()
zs = [onp.load(RES / f"split_half_part{k}.npz") for k in range(3)]
ids = onp.concatenate([z["ids"][:int(z["done"])] for z in zs])
grp = onp.concatenate([z["groups"][:int(z["done"])] for z in zs])
ev = onp.concatenate([z["log_ev"][:int(z["done"])] for z in zs])
names = list(zs[0]["models"])
r2 = ev[:, names.index("C")] - ev[:, names.index("H")]
acc2 = onp.array([(P[str(p)]["data"][63:90, 6] == P[str(p)]["data"][63:90, 7]).mean() for p in ids])
gnum = (grp == "g1").astype(float)
rx, ry = rankdata(r2), rankdata(acc2)
res = lambda a: a - onp.polyval(onp.polyfit(gnum, a, 1), gnum)
rp, pp = spearmanr(res(rx), res(ry))
print(f"  split-half C vs H: group-controlled r_s = {rp:.2f} (p = {pp:.3f}); n = {len(ids)}; "
      f"log BF range {r2.min():.1f} to {r2.max():.1f}; accuracy range {acc2.min():.2f}-{acc2.max():.2f}")
with open(OUT / "fig5_splithalf.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["id", "group", "logbf_C_H", "accuracy_28_54"])
    for i in range(len(ids)):
        w.writerow([ids[i], "BPD" if grp[i] == "g1" else "Controls", f"{r2[i]:.4f}", f"{acc2[i]:.4f}"])
print("wrote fig5_splithalf.csv")
